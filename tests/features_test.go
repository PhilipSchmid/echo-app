func newReadinessDependency(t *testing.T) (string, func(bool)) {
	t.Helper()
	var ready atomic.Bool
	ready.Store(true)
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		if !ready.Load() {
			w.WriteHeader(http.StatusServiceUnavailable)
		}
	}))
	t.Cleanup(server.Close)
	return server.URL, ready.Store
}

func checkRequestDiagnostics(response *http.Response, body map[string]any) error {
	if body["http_host"] != "diagnostic.example:8443" || body["http_request_uri"] != "/test%2Fpath?item=42&encoded=a%2Bb" {
		return fmt.Errorf("host or original request URI missing: %v", body)
	}
	for _, name := range []string{"remote_addr", "local_addr"} {
		address, _ := body[name].(string)
		host, port, err := net.SplitHostPort(address)
		if err != nil || net.ParseIP(host) == nil || port == "" || (name == "remote_addr" && host != body["source_ip"]) {
			return fmt.Errorf("invalid %s: %q", name, address)
		}
	}
	headers, ok := body["headers"].(map[string]any)
	if !ok {
		return fmt.Errorf("request headers missing")
	}
	for name, want := range map[string]string{"Authorization": "[REDACTED]", "Cookie": "[REDACTED]", "X-Forwarded-For": "203.0.113.10", "Forwarded": "for=203.0.113.10;proto=https;host=proxy.example"} {
		values, ok := headers[name].([]any)
		if !ok || len(values) != 1 || values[0] != want {
			return fmt.Errorf("%s: expected %q, got %v", name, want, headers[name])
		}
	}
	if response.Header.Get("Cache-Control") != "no-store" {
		return fmt.Errorf("diagnostic response permits caching")
	}
	if response.TLS == nil {
		if body["tls_version"] != nil {
			return fmt.Errorf("plaintext request reported TLS state")
		}
		return nil
	}
	for name, want := range map[string]string{
		"tls_version":             tls.VersionName(response.TLS.Version),
		"tls_cipher_suite":        tls.CipherSuiteName(response.TLS.CipherSuite),
		"tls_server_name":         "diagnostic.example",
		"tls_negotiated_protocol": response.TLS.NegotiatedProtocol,
	} {
		got, _ := body[name].(string)
		if got != want {
			return fmt.Errorf("%s: expected %q, got %q", name, want, got)
		}
	}
	return nil
}

func checkResponseControls(t *testing.T, client *http.Client, baseURL string) {
	t.Helper()
	for _, tc := range []struct {
		query string
		code  int
		size  int
	}{
		{"status=418&delay=30ms&size=17", http.StatusTeapot, 17},
		{"status=200&delay=0s&size=0", http.StatusOK, 0},
		{"status=599&size=65536", 599, 65536},
		{"status=204&size=17", http.StatusNoContent, 0},
		{"status=199", http.StatusBadRequest, -1},
		{"status=600", http.StatusBadRequest, -1},
		{"status=200&status=201", http.StatusBadRequest, -1},
		{"delay=-1ns", http.StatusBadRequest, -1},
		{"delay=10.000000001s", http.StatusBadRequest, -1},
		{"size=-1", http.StatusBadRequest, -1},
		{"size=65537", http.StatusBadRequest, -1},
	} {
		t.Run(tc.query, func(t *testing.T) {
			start := time.Now()
			response, err := client.Get(baseURL + "/?" + tc.query)
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = response.Body.Close() }()
			data, err := io.ReadAll(io.LimitReader(response.Body, (1<<20)+1))
			if err != nil || response.StatusCode != tc.code {
				t.Fatalf("status=%d, expected %d; body error=%v", response.StatusCode, tc.code, err)
			}
			if tc.size >= 0 && len(data) != tc.size {
				t.Fatalf("expected %d generated bytes, got %d bytes", tc.size, len(data))
			}
			if tc.size >= 0 && tc.code != http.StatusNoContent && (response.ContentLength != int64(tc.size) || response.Header.Get("Content-Type") != "application/octet-stream") {
				t.Fatalf("generated response headers: length=%d type=%q", response.ContentLength, response.Header.Get("Content-Type"))
			}
			if strings.Contains(tc.query, "delay=30ms") && time.Since(start) < 30*time.Millisecond {
				t.Fatal("response arrived before the requested delay")
			}
		})
	}
	request, err := http.NewRequest(http.MethodHead, baseURL+"/?size=17", nil)
	if err != nil {
		t.Fatal(err)
	}
	response, err := client.Do(request)
	if err != nil {
		t.Fatal(err)
	}
	data, readErr := io.ReadAll(response.Body)
	_ = response.Body.Close()
	if readErr != nil || response.StatusCode != http.StatusOK || len(data) != 0 || response.Header.Get("Content-Length") != "17" {
		t.Fatalf("HEAD: length=%q bytes=%d err=%v", response.Header.Get("Content-Length"), len(data), readErr)
	}
}

func prepareFeatureShutdown(t *testing.T, ports map[string]string, setDependencyReady func(bool), host string) func() {
	t.Helper()
	var sockets []*websocket.Conn
	for _, scheme := range []string{"ws", "wss"} {
		port := ports["http"]
		if scheme == "wss" {
			port = ports["tls"]
		}
		transport := &http.Transport{TLSClientConfig: &tls.Config{InsecureSkipVerify: true}} // Self-signed demo certificate.
		t.Cleanup(transport.CloseIdleConnections)
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		conn, response, err := websocket.Dial(ctx, scheme+"://"+net.JoinHostPort(host, port)+"/ws", &websocket.DialOptions{HTTPClient: &http.Client{Transport: transport, Timeout: 3 * time.Second}})
		cancel()
		if err != nil {
			if response != nil {
				_ = response.Body.Close()
			}
			t.Fatalf("%s WebSocket dial: %v", scheme, err)
		}
		t.Cleanup(func() { _ = conn.CloseNow() })
		for _, message := range []struct {
			kind websocket.MessageType
			data []byte
		}{{websocket.MessageText, []byte("echo")}, {websocket.MessageBinary, []byte{0, 1, 2, 255}}} {
			ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
			if err := conn.Write(ctx, message.kind, message.data); err != nil {
				cancel()
				t.Fatal(err)
			}
			kind, data, err := conn.Read(ctx)
			cancel()
			if err != nil || kind != message.kind || !bytes.Equal(data, message.data) {
				t.Fatalf("%s WebSocket echo: kind=%v data=%v err=%v", scheme, kind, data, err)
			}
		}
		sockets = append(sockets, conn)
	}
	conn, err := grpc.NewClient(net.JoinHostPort(host, ports["grpc"]), grpc.WithTransportCredentials(insecure.NewCredentials()))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = conn.Close() })
	client := healthpb.NewHealthClient(conn)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	t.Cleanup(cancel)
	for _, service := range []string{"", "echo.EchoService"} {
		response, err := client.Check(ctx, &healthpb.HealthCheckRequest{Service: service})
		if err != nil || response.Status != healthpb.HealthCheckResponse_SERVING {
			t.Fatalf("gRPC health Check(%q): response=%v err=%v", service, response, err)
		}
	}
	watch, err := client.Watch(ctx, &healthpb.HealthCheckRequest{Service: "echo.EchoService"})
	if err != nil {
		t.Fatal(err)
	}
	for _, ready := range []bool{true, false, true} {
		setDependencyReady(ready)
		want := healthpb.HealthCheckResponse_NOT_SERVING
		if ready {
			want = healthpb.HealthCheckResponse_SERVING
		}
		response, err := watch.Recv()
		if err != nil || response.Status != want {
			t.Fatalf("gRPC health Watch: expected %v, response=%v err=%v", want, response, err)
		}
		requestCtx, stop := context.WithTimeout(context.Background(), 2*time.Second)
		request, err := http.NewRequestWithContext(requestCtx, http.MethodGet, "http://"+net.JoinHostPort(host, ports["metrics"])+"/ready", nil)
		if err != nil {
			stop()
			t.Fatal(err)
		}
		responseHTTP, err := http.DefaultClient.Do(request)
		stop()
		if err != nil {
			t.Fatal(err)
		}
		_ = responseHTTP.Body.Close()
		if (responseHTTP.StatusCode == http.StatusOK) != ready {
			t.Fatalf("HTTP and gRPC readiness disagree: HTTP status=%d ready=%v", responseHTTP.StatusCode, ready)
		}
	}
	return func() {
		for _, socket := range sockets {
			ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
			_, _, err := socket.Read(ctx)
			cancel()
			if err == nil || errors.Is(err, context.DeadlineExceeded) {
				t.Fatalf("WebSocket did not close during shutdown: %v", err)
			}
		}
		notServing := false
		for {
			response, err := watch.Recv()
			if errors.Is(err, io.EOF) {
				break
			}
			if err != nil || response.Status != healthpb.HealthCheckResponse_NOT_SERVING {
				t.Fatalf("shutdown health Watch: response=%v err=%v", response, err)
			}
			notServing = true
		}
		if !notServing {
			t.Fatal("health Watch closed without reporting NOT_SERVING")
		}
	}
}

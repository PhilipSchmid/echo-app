func TestResponseControlBounds(t *testing.T) {
	for _, query := range []string{"", "status=200", "status=599", "delay=0s", "delay=10s", "size=0", "size=1048576", "status=503&delay=1s&size=42"} {
		t.Run(query, func(t *testing.T) {
			_, err := parseResponseControls(query)
			require.NoError(t, err)
		})
	}
	for _, query := range []string{
		"status=199", "status=600", "status=hello", "status=", "status=200&status=201",
		"delay=-1s", "delay=10.001s", "delay=forever", "delay=", "delay=0&delay=1s",
		"size=-1", "size=1048577", "size=huge", "size=", "size=1&size=2", "size=9999999999999999999999999", "%ZZ=1",
	} {
		t.Run(query, func(t *testing.T) {
			req := httptest.NewRequest(http.MethodGet, "/", nil)
			req.URL.RawQuery = query
			w := httptest.NewRecorder()
			HTTPHandler(&config.Config{ResponseControls: true, MaxRequestSize: 4}, "HTTP")(w, req)
			assert.Equal(t, http.StatusBadRequest, w.Code)
		})
	}
}

func TestResponseControlsDisabledByDefault(t *testing.T) {
	w := httptest.NewRecorder()
	HTTPHandler(&config.Config{MaxRequestSize: 4}, "HTTP")(w, httptest.NewRequest(http.MethodGet, "/?status=503&delay=invalid&size=invalid", nil))
	assert.Equal(t, http.StatusOK, w.Code)
	var response HTTPResponse
	require.NoError(t, json.Unmarshal(w.Body.Bytes(), &response))
	assert.Equal(t, "/", response.HTTPEndpoint)
}

func TestResponseControlHTTPBodySemantics(t *testing.T) {
	for _, tc := range []struct {
		name          string
		method        string
		query         string
		status        int
		bodyLength    int
		contentLength string
	}{
		{"generated bytes", http.MethodGet, "status=503&size=32", 503, 32, "32"},
		{"empty generated body", http.MethodGet, "size=0", 200, 0, "0"},
		{"maximum generated body", http.MethodGet, "size=1048576", 200, 1048576, "1048576"},
		{"HEAD generated body", http.MethodHead, "size=32", 200, 0, "32"},
		{"204", http.MethodGet, "status=204&size=32", 204, 0, ""},
		{"205", http.MethodGet, "status=205&size=32", 205, 0, ""},
		{"304", http.MethodGet, "status=304&size=32", 304, 0, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			w := httptest.NewRecorder()
			HTTPHandler(&config.Config{ResponseControls: true, MaxRequestSize: 4}, "HTTP")(w, httptest.NewRequest(tc.method, "/?"+tc.query, nil))
			assert.Equal(t, tc.status, w.Code)
			assert.Equal(t, tc.bodyLength, w.Body.Len())
			assert.Equal(t, tc.contentLength, w.Header().Get("Content-Length"))
			assert.Equal(t, "application/octet-stream", w.Header().Get("Content-Type"))
		})
	}
	w := httptest.NewRecorder()
	HTTPHandler(&config.Config{MaxRequestSize: 4}, "HTTP")(w, httptest.NewRequest(http.MethodHead, "/", nil))
	assert.Empty(t, w.Body.String())
	length, err := strconv.Atoi(w.Header().Get("Content-Length"))
	require.NoError(t, err)
	assert.Positive(t, length)
}

func TestResponseDelayAndCancellation(t *testing.T) {
	handler := HTTPHandler(&config.Config{ResponseControls: true, MaxRequestSize: 4}, "HTTP")
	started := time.Now()
	w := httptest.NewRecorder()
	handler(w, httptest.NewRequest(http.MethodGet, "/?delay=20ms", nil))
	assert.Equal(t, http.StatusOK, w.Code)
	assert.GreaterOrEqual(t, time.Since(started), 20*time.Millisecond)

	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	req := httptest.NewRequest(http.MethodGet, "/?delay=10s", nil).WithContext(ctx)
	w = httptest.NewRecorder()
	started = time.Now()
	handler(w, req)
	assert.Less(t, time.Since(started), time.Second)
	assert.Empty(t, w.Body.String())
}
